from pydantic import BaseModel


class SalesEnablementOutput(BaseModel):
    """
    Pydantic schema enforced on Gemini's raw structured output.

    The email is requested as an explicit list of 6 paragraphs (instead of one
    free-form string) so paragraph breaks can never be lost to LLM formatting
    — the adapter joins them itself.
    """

    discovery_questions: list[str]
    talking_points: list[str]
    outreach_subject: str
    outreach_paragraphs: list[str]


class SalesEnablementResult(BaseModel):
    """
    Immutable value object representing the sales enablement content
    generated by the Gemini synthesis step.

    Contains:
    - discovery_questions: Questions for the BD team to ask the client.
    - talking_points: Technical talking points for BD pitch (no internal project names).
    - outreach_template: Formal cold email written from a BD perspective
      (paragraphs joined with blank lines).
    """

    discovery_questions: list[str]
    talking_points: list[str]
    outreach_subject: str
    outreach_template: str

    model_config = {"frozen": True}
